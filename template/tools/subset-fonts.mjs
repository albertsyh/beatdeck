/**
 * Subset the non-Latin faces listed in deck.config.js (fonts.scripts) to
 * exactly the characters the copy uses, and write src/fonts-scripts.css.
 *
 *   bun run fonts:subset
 *
 * A complete CJK face is 17 MB; the deck's copy uses a few hundred distinct
 * characters, so the face it needs is ~100 KB. This walks every string in
 * every language (src/strings/index.js → allText) and embeds only those.
 *
 * REQUIREMENTS: a .venv with fonttools —
 *   python3 -m venv .venv && .venv/bin/pip install "fonttools[woff] brotli"
 * Source faces are downloaded once into tools/.fontcache/ (gitignored).
 *
 * The output is committed. Re-run after ANY change to translated copy; if
 * you forget, `bun run build` fails naming the uncovered character.
 */
import { readFile, writeFile, mkdir, access } from "node:fs/promises";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { resolve } from "node:path";
import { resolveScript } from "./script-faces.mjs";

const run = promisify(execFile);
const PY = process.platform === "win32" ? ".venv/Scripts/python.exe" : ".venv/bin/python";
const CACHE = "tools/.fontcache";
const OUT = "src/fonts-scripts.css";

const kb = (n) => (n / 1024).toFixed(0) + "KB";
const fail = (m) => { console.error(m); process.exit(1); };
const exists = (p) => access(p).then(() => true, () => false);

const config = (await import(resolve("deck.config.js"))).default;
const faces = (config.fonts?.scripts || []).map(resolveScript);
if (!faces.length) {
  console.log("deck.config.js lists no fonts.scripts; nothing to subset.");
  process.exit(0);
}
if (!(await exists(PY))) fail(`${PY} not found.\nRun:  python3 -m venv .venv && .venv/bin/pip install "fonttools[woff] brotli"`);

await mkdir(CACHE, { recursive: true });
for (const face of faces) {
  const path = `${CACHE}/${face.file}`;
  if (await exists(path)) continue;
  console.log(`fetching ${face.file} …`);
  const res = await fetch(face.url);
  if (!res.ok) fail(`${face.url} returned ${res.status}`);
  await writeFile(path, Buffer.from(await res.arrayBuffer()));
}

function coveredBy(css) {
  const set = new Set();
  for (const [, body] of css.matchAll(/unicode-range:\s*([^;}]+)/g)) {
    for (const part of body.split(",")) {
      const m = /^\s*U\+([0-9A-Fa-f]+)(?:-([0-9A-Fa-f]+))?\s*$/.exec(part);
      if (!m) continue;
      const lo = parseInt(m[1], 16), hi = m[2] ? parseInt(m[2], 16) : lo;
      for (let cp = lo; cp <= hi; cp++) set.add(cp);
    }
  }
  return set;
}
function unicodeRange(codepoints) {
  const cps = [...codepoints].sort((a, b) => a - b);
  const hex = (n) => n.toString(16).toUpperCase().padStart(4, "0");
  const parts = [];
  let start = cps[0], prev = cps[0];
  for (const cp of cps.slice(1)) {
    if (cp === prev + 1) { prev = cp; continue; }
    parts.push(start === prev ? `U+${hex(start)}` : `U+${hex(start)}-${hex(prev)}`);
    start = prev = cp;
  }
  parts.push(start === prev ? `U+${hex(start)}` : `U+${hex(start)}-${hex(prev)}`);
  return parts.join(", ");
}

const strings = await import(resolve("src/strings/index.js"));
/* everything the Latin faces already carry stays in them, so shared
   punctuation renders in the deck's own face rather than in Noto */
const latin = coveredBy(await readFile("src/fonts.css", "utf8"));
const needed = new Set();
for (const ch of strings.allText()) {
  if (/\s/.test(ch)) continue;
  const cp = ch.codePointAt(0);
  if (!latin.has(cp)) needed.add(cp);
}
let remaining = [...needed];
if (!remaining.length) {
  await writeFile(OUT, "/* GENERATED by tools/subset-fonts.mjs — no non-Latin characters in the copy. */\n", "utf8");
  console.log(`${OUT} written — nothing to subset.`);
  process.exit(0);
}

const blocks = [];
let total = 0;
for (const face of faces) {
  const src = `${CACHE}/${face.file}`;
  const { stdout } = await run(PY, ["-c", `
import sys
from fontTools.ttLib import TTFont
f = TTFont(sys.argv[1], lazy=True)
have = set()
for t in f["cmap"].tables:
    have |= set(t.cmap.keys())
print(" ".join(str(c) for c in sorted(have)))
`, src], { maxBuffer: 64 * 1024 * 1024 });
  const have = new Set(stdout.trim().split(/\s+/).map(Number));
  const mine = remaining.filter((cp) => have.has(cp));
  if (!mine.length) { console.log(`  ${face.family}: no characters needed`); continue; }
  remaining = remaining.filter((cp) => !have.has(cp));

  const tmp = `${CACHE}/.${config.name}-${face.family.replace(/\W+/g, "-")}`;
  await writeFile(`${tmp}.txt`, mine.map((cp) => String.fromCodePoint(cp)).join(""), "utf8");
  let input = src;
  if (face.pin) {
    await run(PY, ["-m", "fontTools.varLib.instancer", src, face.pin, "-o", `${tmp}-pinned.ttf`]);
    input = `${tmp}-pinned.ttf`;
  }
  await run(PY, ["-m", "fontTools.subset", input, `--text-file=${tmp}.txt`, "--flavor=woff2",
    "--layout-features=*", "--no-hinting", "--desubroutinize", `--output-file=${tmp}.woff2`]);
  const bytes = await readFile(`${tmp}.woff2`);
  const b64 = bytes.toString("base64");
  total += b64.length;
  console.log(`  ${face.family.padEnd(22)} ${String(mine.length).padStart(4)} glyphs  ${kb(bytes.length)} woff2  ${kb(b64.length)} base64`);
  blocks.push(`/* ${face.family} — ${face.note}, subsetted to the ${mine.length} characters this deck uses */
@font-face{
  font-family: '${face.family}';
  font-style: normal;
  font-weight: 400 700;
  font-display: swap;
  src: url(data:font/woff2;base64,${b64}) format('woff2');
  unicode-range: ${unicodeRange(mine)};
}`);
}

if (remaining.length) {
  const show = remaining.slice(0, 8).map((cp) => `"${String.fromCodePoint(cp)}" U+${cp.toString(16).toUpperCase().padStart(4, "0")}`).join(", ");
  console.warn(`warning: ${remaining.length} character(s) are in no listed script face: ${show}. Add the script to fonts.scripts; the build will refuse them.`);
}

await writeFile(OUT, `/* GENERATED by tools/subset-fonts.mjs — do not edit. Run \`bun run fonts:subset\`
   after changing any copy in src/strings/. Noto faces are Open Font License. */

${blocks.join("\n\n")}
`, "utf8");
console.log(`${OUT} written — ${kb(total)} base64 across ${blocks.length} face(s)`);
